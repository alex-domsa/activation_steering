"""Project settings: the one place to change the model, the contrast, the seed and the folders."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]          # the repository folder

MODEL = "Qwen/Qwen2.5-1.5B-Instruct"                # also used: "meta-llama/Llama-3.2-1B" (gated), "Qwen/Qwen2.5-0.5B-Instruct"
CONTRAST = "analogy_vs_unrelated"                   # see data.CONTRASTS
SEED = 0                                            # fixed seed: same sample, split and random controls every run

DATA_DIR = ROOT / "data"
STORYANALOGY_CSV = DATA_DIR / "StoryAnalogy.csv"


def model_tag(model=MODEL):
    """'Qwen/Qwen2.5-1.5B-Instruct' -> 'Qwen__Qwen2.5-1.5B-Instruct' (safe as a folder name)."""
    return model.replace("/", "__")


# Every model and contrast gets its own folders, so runs never overwrite each other.
CACHE_DIR = ROOT / "cache" / model_tag() / CONTRAST            # activations, generated by the experiments (not committed)
RESULTS_DIR = ROOT / "results" / model_tag() / CONTRAST        # full result tables (not committed)
SUMMARY_DIR = ROOT / "results" / "summary"                     # final tables and plots (committed)
